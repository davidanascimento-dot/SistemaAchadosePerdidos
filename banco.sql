create table if not exists public.objetos (
    id bigint generated by default as identity primary key,
    descricao text not null,
    categoria text not null,
    local text not null,
    data_registro date not null default current_date,
    situacao text not null default 'Disponível'
        check (situacao in ('Disponível', 'Devolvido')),
    criado_em timestamptz not null default now()
);

-- segurança (RLS): libera o CRUD para a chave pública (anon)
alter table public.objetos enable row level security;

drop policy if exists "acesso_total_objetos" on public.objetos;
create policy "acesso_total_objetos"
    on public.objetos
    for all
    using (true)
    with check (true);

-- permissões para a API pública
grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.objetos to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- Índice para acelerar a busca por descrição/local
create index if not exists objetos_busca_idx
    on public.objetos using gin (to_tsvector('portuguese', descricao || ' ' || local));
